"""Per-role egress scoping: squid config generated from the role library.

The global allowlist (deploy/proxy/allowlist.txt) is the floor EVERY sandbox
gets — the model API lives there, so a sandbox without it cannot run at all.
A role whose ``tool_permissions.egress_allow`` names domains gets its OWN
squid listening port whose reachable set is the floor plus its own dstdomain
file — default-deny beyond that — and the runner points that role's
containers at that port. Scoping is network-enforced per role, not suggested
per prompt.

The port is a pure function of the role slug (stable across hosts and
restarts, no shared state between the generator and the runner). Collisions
are detected loudly at generation time; renaming a role slug resolves one.

On the compose box the runner regenerates and reloads squid automatically.
Multi-box: `yaaf egress-sync`, then `docker exec <proxy> squid -k reconfigure`
(a plain container HUP dies in the squid image's bash entrypoint).
"""

from __future__ import annotations

import zlib
from pathlib import Path

from sqlalchemy import select
from sqlalchemy.orm import Session

from yaaf.core.models import Project, Role, RoleVersion

PORT_BASE = 3200
PORT_SPAN = 700  # 3200-3899 inside the sandbox network; never published


def role_port(slug: str) -> int:
    return PORT_BASE + zlib.crc32(slug.encode()) % PORT_SPAN


def _latest_permissions(session: Session, role_slug: str) -> dict:
    role = session.execute(select(Role).where(Role.slug == role_slug)).scalar_one_or_none()
    if role is None:
        return {}
    version = session.execute(
        select(RoleVersion).where(RoleVersion.role_id == role.id)
        .order_by(RoleVersion.version.desc()).limit(1)
    ).scalar_one_or_none()
    return (version.tool_permissions or {}) if version else {}


def role_egress_domains(session: Session, role_slug: str) -> list[str]:
    """The latest role version's egress_allow, normalized for squid dstdomain
    (leading dot = domain plus subdomains)."""
    domains = _latest_permissions(session, role_slug).get("egress_allow", [])
    return [d if d.startswith(".") else f".{d}" for d in domains if d.strip()]


def role_egress_ports(session: Session, role_slug: str) -> list[int]:
    """Extra destination ports beyond 80/443 (egress_ports) — MCP servers and
    internal APIs rarely sit on the well-known ports."""
    return [int(p) for p in _latest_permissions(session, role_slug).get("egress_ports", [])]


def role_egress_unrestricted(session: Session, role_slug: str) -> bool:
    """True when the role's port allows every host — for work whose sources
    cannot be enumerated in advance (checking a claim, chasing a citation,
    validating against whatever the answer turns out to name).

    A flag rather than a wildcard entry in the domain list, for two reasons:
    squid has no match-all dstdomain (a bare '.' is refused, not universal),
    and a magic string buried in a list of real domains is a hole no reader
    would see. Port discipline still applies — open web means 80/443 plus
    whatever egress_ports declares, not every port on the internet."""
    return bool(_latest_permissions(session, role_slug).get("egress_unrestricted"))


def data_source_extras(session: Session) -> dict[str, tuple[list[str], list[int]]]:
    """Per role slug: (hosts, ports) derived from every project's data sources
    (config.mcp_servers). Saving a data source in the UI is enough — nobody
    hand-maintains egress for it. Host/port live plaintext in project config
    precisely so this derivation never decrypts anything."""
    extras: dict[str, tuple[list[str], list[int]]] = {}
    for project in session.execute(select(Project)).scalars():
        for source in (project.integrations or {}).get("mcp_servers", []):
            host, port = source.get("url_host"), source.get("url_port")
            if not host:
                continue
            for slug in source.get("roles", []):
                hosts, ports = extras.setdefault(slug, ([], []))
                if host not in hosts:
                    hosts.append(host)
                if port and port not in (80, 443) and port not in ports:
                    ports.append(port)
    return extras


def build(session: Session) -> tuple[dict[str, int], dict[str, str]]:
    """Pure content: ({role_slug: port}, {filename: file content}). The API
    serves this to the CLI, which writes the files on the compose host — the
    server has DB access but not the deploy directory; the CLI has the deploy
    directory but not the DB."""
    assignments: dict[str, int] = {}
    ports_seen: dict[int, str] = {}
    files: dict[str, str] = {}
    lines = [
        "# GENERATED by `yaaf egress-sync` — do not edit by hand.",
        "# One listening port per scoped role; default-deny beyond the global",
        "# floor plus the role's own list. A role marked egress_unrestricted",
        "# gets a port with no destination ACL — every host, still 80/443.",
        "",
        "# The floor: every sandbox keeps the global allowlist (the model API",
        "# lives there) — a role's own list only ever adds, never subtracts.",
        'acl dst_floor dstdomain "/etc/squid/allowlist.txt"',
    ]
    extras = data_source_extras(session)
    for role in session.execute(select(Role).order_by(Role.slug)).scalars():
        unrestricted = role_egress_unrestricted(session, role.slug)
        domains = role_egress_domains(session, role.slug)
        extra_hosts, extra_ports = extras.get(role.slug, ([], []))
        domains += [h if h.startswith(".") else f".{h}" for h in extra_hosts
                    if f".{h}" not in domains and h not in domains]
        if not domains and not unrestricted:
            continue
        port = role_port(role.slug)
        if port in ports_seen:
            raise RuntimeError(
                f"egress port collision: roles '{ports_seen[port]}' and '{role.slug}' both "
                f"hash to {port}. Rename one slug — the port must be a pure function of it."
            )
        ports_seen[port] = role.slug
        assignments[role.slug] = port
        safe = role.slug.replace("-", "_")
        # Destination ports: 80/443 plus whatever the role declares
        # (egress_ports) — the CONNECT rule shares the list so TLS on a
        # custom port (the usual MCP-server shape) works.
        declared = role_egress_ports(session, role.slug)
        ok_ports = " ".join(str(p) for p in
                            [80, 443, *declared, *[p for p in extra_ports
                                                   if p not in declared]])
        lines += [
            "",
            f"http_port {port} name=role_{safe}",
            f"acl port_{safe} myportname role_{safe}",
        ]
        if not unrestricted:
            files[f"allowlist_{safe}.txt"] = "\n".join(domains) + "\n"
            lines.append(
                f'acl dst_{safe} dstdomain "/etc/squid/generated/allowlist_{safe}.txt"'
            )
        lines += [
            f"acl ok_ports_{safe} port {ok_ports}",
            f"http_access deny port_{safe} !ok_ports_{safe}",
            f"http_access deny port_{safe} CONNECT !ok_ports_{safe}",
        ]
        if unrestricted:
            # Open web: no destination ACL at all. The port discipline above
            # still stands, so this is every HOST, not every port.
            lines.append(f"http_access allow port_{safe}")
        else:
            lines += [
                f"http_access allow port_{safe} dst_floor",
                f"http_access allow port_{safe} dst_{safe}",
                f"http_access deny port_{safe}",
            ]
    files["roles.conf"] = "\n".join(lines) + "\n"
    return assignments, files


def generate(session: Session, out_dir: Path) -> dict[str, int]:
    """Write generated/roles.conf + one allowlist file per scoped role.
    Returns {role_slug: port}. Roles without egress_allow stay on the default
    port and the global allowlist."""
    assignments, files = build(session)
    out_dir.mkdir(parents=True, exist_ok=True)
    for name, content in files.items():
        (out_dir / name).write_text(content)
    return assignments
