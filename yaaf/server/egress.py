"""Per-role egress scoping: squid config generated from the role library.

The global allowlist (deploy/proxy/allowlist.txt) is the floor every sandbox
gets on the default proxy port. A role whose ``tool_permissions.egress_allow``
names domains gets its OWN squid listening port with its OWN dstdomain file —
default-deny beyond it — and the runner points that role's containers at that
port. Scoping is therefore network-enforced per role, not suggested per prompt.

The port is a pure function of the role slug (stable across hosts and
restarts, no shared state between the generator and the runner). Collisions
are detected loudly at generation time; renaming a role slug resolves one.

Regenerate with `yaaf egress sync` after editing roles, then HUP the proxy.
"""

from __future__ import annotations

import zlib
from pathlib import Path

from sqlalchemy import select
from sqlalchemy.orm import Session

from yaaf.core.models import Role, RoleVersion

PORT_BASE = 3200
PORT_SPAN = 700  # 3200-3899 inside the sandbox network; never published


def role_port(slug: str) -> int:
    return PORT_BASE + zlib.crc32(slug.encode()) % PORT_SPAN


def role_egress_domains(session: Session, role_slug: str) -> list[str]:
    """The latest role version's egress_allow, normalized for squid dstdomain
    (leading dot = domain plus subdomains)."""
    role = session.execute(select(Role).where(Role.slug == role_slug)).scalar_one_or_none()
    if role is None:
        return []
    version = session.execute(
        select(RoleVersion).where(RoleVersion.role_id == role.id)
        .order_by(RoleVersion.version.desc()).limit(1)
    ).scalar_one_or_none()
    domains = (version.tool_permissions or {}).get("egress_allow", []) if version else []
    return [d if d.startswith(".") else f".{d}" for d in domains if d.strip()]


def generate(session: Session, out_dir: Path) -> dict[str, int]:
    """Write generated/roles.conf + one allowlist file per scoped role.
    Returns {role_slug: port}. Roles without egress_allow stay on the default
    port and the global allowlist."""
    out_dir.mkdir(parents=True, exist_ok=True)
    assignments: dict[str, int] = {}
    ports_seen: dict[int, str] = {}
    lines = [
        "# GENERATED by `yaaf egress sync` — do not edit by hand.",
        "# One listening port per scoped role; default-deny beyond its list.",
    ]
    for role in session.execute(select(Role).order_by(Role.slug)).scalars():
        domains = role_egress_domains(session, role.slug)
        if not domains:
            continue
        port = role_port(role.slug)
        if port in ports_seen:
            raise RuntimeError(
                f"egress port collision: roles '{ports_seen[port]}' and '{role.slug}' both "
                f"hash to {port}. Rename one slug — the port must be a pure function of it."
            )
        ports_seen[port] = role.slug
        assignments[role.slug] = port
        safe = role.slug.replace("-", "_")
        (out_dir / f"allowlist_{safe}.txt").write_text("\n".join(domains) + "\n")
        lines += [
            "",
            f"http_port {port} name=role_{safe}",
            f"acl port_{safe} myportname role_{safe}",
            f'acl dst_{safe} dstdomain "/etc/squid/generated/allowlist_{safe}.txt"',
            f"http_access deny port_{safe} !safe_ports",
            f"http_access deny port_{safe} CONNECT !ssl_ports",
            f"http_access allow port_{safe} dst_{safe}",
            f"http_access deny port_{safe}",
        ]
    (out_dir / "roles.conf").write_text("\n".join(lines) + "\n")
    return assignments
